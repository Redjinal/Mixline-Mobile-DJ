#!/usr/bin/env python3
"""Generate deterministic FIXTURE waveform peak arrays for the prototype.

These are not analysis results. Each track gets a seeded pseudo-random envelope
with beat-synchronous transients so waveform components have something plausible
to draw. The output carries a `_fixture` note and every consumer renders a
FIXTURE mark.

Run:  python3 design/tools/gen_waveforms.py
"""
from pathlib import Path
import json
import math
import random

ROOT = Path(__file__).resolve().parents[1] / "prototype" / "fixtures"
TRACKS = ROOT / "tracks.json"
OUT = ROOT / "waveforms.json"
BINS = 1024


def envelope(rng: random.Random, n: int, phrases: int) -> list[float]:
    """Slow energy curve with phrase-level steps and gentle noise."""
    steps = []
    level = 0.35
    for _ in range(max(phrases, 4)):
        level = min(0.95, max(0.15, level + rng.uniform(-0.25, 0.3)))
        steps.append(level)
    out = []
    for i in range(n):
        p = i / n * len(steps)
        a = steps[int(p) % len(steps)]
        b = steps[(int(p) + 1) % len(steps)]
        t = p - int(p)
        base = a * (1 - t) + b * t
        base *= 0.9 + 0.1 * math.sin(i / n * math.pi * 7 + rng.random() * 0.2)
        out.append(base)
    # Intro and outro taper
    for i in range(n):
        edge = min(i, n - 1 - i) / (n * 0.06)
        if edge < 1:
            out[i] *= 0.25 + 0.75 * edge
    return out


def track_wave(track: dict) -> dict:
    rng = random.Random(track["id"])
    duration = track["durationSec"]
    bpm = track.get("bpm") or 120.0
    beat_sec = 60.0 / bpm
    env = envelope(rng, BINS, max(1, len(track.get("phrases", [])) or 4))
    peaks, rms, lows, highs = [], [], [], []
    for i in range(BINS):
        t0 = i / BINS * duration
        # transient if a beat lands in this bin
        bin_len = duration / BINS
        beat_phase = (t0 % beat_sec) / beat_sec
        transient = 1.0 if beat_phase < (bin_len / beat_sec) else 0.0
        kick = 0.55 + 0.45 * transient
        noise = rng.uniform(0.75, 1.0)
        amp = min(1.0, env[i] * kick * noise)
        peaks.append(round(amp, 3))
        rms.append(round(amp * rng.uniform(0.45, 0.7), 3))
        lows.append(round(amp * (0.5 + 0.5 * transient) * rng.uniform(0.6, 1.0), 3))
        highs.append(round(amp * rng.uniform(0.2, 0.6), 3))
    beats = []
    t = 0.0
    while t < duration:
        beats.append(round(t, 3))
        t += beat_sec
    downbeats = beats[::4]
    uncertain_after = None
    if track.get("gridConfidence") == "low":
        uncertain_after = round(duration * 0.46, 1)
    return {
        "trackId": track["id"],
        "durationSec": duration,
        "bins": BINS,
        "peaks": peaks,
        "rms": rms,
        "lows": lows,
        "highs": highs,
        "beats": beats,
        "downbeats": downbeats,
        "uncertainAfterSec": uncertain_after,
        "silence": [] if track["id"] != "longtitle" else [[300.0, 306.5]],
    }


def main() -> None:
    tracks = json.loads(TRACKS.read_text())["tracks"]
    waves = {t["id"]: track_wave(t) for t in tracks if t.get("availability") in ("ready", "missing", "permission-missing")}
    OUT.write_text(json.dumps({
        "_fixture": "Deterministic synthetic peak arrays generated by design/tools/gen_waveforms.py. Not analysis of any audio.",
        "generator": "gen_waveforms.py",
        "bins": BINS,
        "waveforms": waves,
    }, separators=(",", ":")))
    print(f"wrote {OUT} ({len(waves)} waveforms)")


if __name__ == "__main__":
    main()
