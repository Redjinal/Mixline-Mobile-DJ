#!/usr/bin/env node
// Generate design/spec tables from the live registry:
//   screen-state-index.md      every screen, its states (exercised vs drawn), orientations, FR ids
//   control-requirement-map.md FR id -> screens and components that serve it, plus uncovered FRs
//   components.md              component contract table
// Hand-written notes live in other files; these three are regenerated.
//
//   node design/tools/build_spec.mjs [--port 8792]
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startServer, openPrototype, renderScreen, listScreens } from './smoke.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '..');
const REPO = resolve(ROOT, '..');
const args = Object.fromEntries(process.argv.slice(2).map((a, i, l) => a.startsWith('--') ? [a.slice(2), l[i + 1] && !l[i + 1].startsWith('--') ? l[i + 1] : true] : []).filter(Boolean));
const PORT = Number(args.port || 8792);
const register = JSON.parse(readFileSync(resolve(REPO, 'docs/planning/v1_0/contracts/requirements_register.json'), 'utf8'));
const FAMILY_TITLES = { launch: 'Launch, library and crates', preparation: 'Track preparation', routing: 'Readiness and routing', performance: 'Performance and mixer', pads: 'Pads, loops, FX and stems', sampler: 'Sampler and sequencer', queue: 'Queue and automix', recording: 'Recording and history', sources: 'Sources and downloads', parday: 'ParDay', av: 'Video, karaoke, broadcast and microphone', system: 'Plugin rack, settings and recovery', foundation: 'Foundation' };

async function main() {
  mkdirSync(resolve(ROOT, 'spec'), { recursive: true });
  const server = await startServer(PORT);
  const browser = await chromium.launch();
  try {
    const { page } = await openPrototype(browser, PORT);
    const screens = await listScreens(page);
    const components = await page.evaluate(() => window.mdj.components());
    // Collect data-fr usage per screen by rendering each screen's default state in portrait.
    const frByScreen = {};
    for (const sc of screens) {
      await renderScreen(page, { screen: sc.id, state: null, o: 'portrait' });
      const ids = await page.evaluate(() => Array.from(document.querySelectorAll('#device [data-fr]')).flatMap((el) => el.dataset.fr.split(/\s+/)).filter(Boolean));
      frByScreen[sc.id] = Array.from(new Set([...sc.fr, ...ids])).sort();
    }
    writeFileSync(resolve(ROOT, 'spec/screen-state-index.md'), screenIndex(screens, frByScreen));
    writeFileSync(resolve(ROOT, 'spec/control-requirement-map.md'), frMap(screens, components, frByScreen));
    writeFileSync(resolve(ROOT, 'spec/components.md'), componentTable(components));
    console.log(`wrote spec tables for ${screens.length} screens and ${components.length} components`);
  } finally {
    await browser.close();
    server.kill();
  }
}

function screenIndex(screens, frByScreen) {
  const fams = {};
  for (const sc of screens) (fams[sc.family] ||= []).push(sc);
  const lines = ['# Screen and state index', '', 'Generated by `design/tools/build_spec.mjs` from the prototype registry. **Exercised** = reached by a tap in the prototype; **drawn** = reachable only through the state switcher. Both are design states, not implemented behaviour.', ''];
  let total = 0, exercised = 0;
  for (const [fam, list] of Object.entries(fams)) {
    lines.push(`## ${FAMILY_TITLES[fam] || fam}`, '', '| Screen | Id | Orientations | Shell | State | Label | Exercised | Scenario |', '| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const sc of list) {
      const states = Object.entries(sc.states);
      states.forEach(([sid, st], i) => {
        total++; if (st.exercised) exercised++;
        lines.push(`| ${i === 0 ? sc.title : ''} | ${i === 0 ? `\`${sc.id}\`` : ''} | ${i === 0 ? sc.orientations.join(', ') : ''} | ${i === 0 ? (sc.shell ? 'yes' : 'no') : ''} | \`${sid}\` | ${st.label} | ${st.exercised ? 'exercised' : 'drawn'} | ${st.scenario || '—'} |`);
      });
      lines.push(`| | | | | | *FR:* ${frByScreen[sc.id].join(', ') || '—'} | | |`);
    }
    lines.push('');
  }
  lines.unshift(`**${screens.length} screens · ${total} states · ${exercised} exercised · ${total - exercised} drawn**`, '');
  lines.splice(0, 0, '');
  return lines.join('\n');
}

function frMap(screens, components, frByScreen) {
  const map = {};
  for (const r of register.requirements) map[r.id] = { requirement: r.requirement, screens: [], components: [] };
  for (const sc of screens) for (const id of frByScreen[sc.id]) if (map[id]) map[id].screens.push(sc.id);
  for (const c of components) for (const id of c.fr) if (map[id]) map[id].components.push(c.tag);
  const lines = ['# Control-to-requirement map', '', 'Generated by `design/tools/build_spec.mjs`. Each FR from `requirements_register.json` lists the screens (via declared `fr` and rendered `data-fr`) and components that serve it in the prototype. Coverage here means *designed*, not implemented or verified.', '', '| FR | Requirement | Screens | Components |', '| --- | --- | --- | --- |'];
  const uncovered = [];
  for (const [id, m] of Object.entries(map)) {
    if (!m.screens.length && !m.components.length) uncovered.push(id);
    lines.push(`| ${id} | ${m.requirement.slice(0, 90)}${m.requirement.length > 90 ? '…' : ''} | ${m.screens.map((s) => `\`${s}\``).join(', ') || '—'} | ${m.components.map((c) => `\`${c}\``).join(', ') || '—'} |`);
  }
  lines.push('', `## Not yet represented in the prototype (${uncovered.length})`, '', uncovered.length ? uncovered.map((id) => `- ${id}: ${map[id].requirement}`).join('\n') : 'All functional requirements are referenced by at least one screen or component.', '');
  return lines.join('\n');
}

function componentTable(components) {
  const lines = ['# Component contracts', '', 'Generated by `design/tools/build_spec.mjs` from the component registry.', '', '| Tag | States | FR | Hit (dp) | Fixture mark |', '| --- | --- | --- | --- | --- |'];
  for (const c of components) lines.push(`| \`${c.tag}\` | ${c.states.join(', ')} | ${c.fr.join(', ') || '—'} | ${c.hit || 'n/a'} | ${c.fixture ? 'yes' : '—'} |`);
  return lines.join('\n') + '\n';
}

main().catch((e) => { console.error(e); process.exit(1); });
