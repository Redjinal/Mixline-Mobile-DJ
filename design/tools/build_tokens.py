#!/usr/bin/env python3
"""Generate design/prototype/tokens/tokens.css from tokens.json.

Run from anywhere:  python3 design/tools/build_tokens.py
The output is committed so the prototype needs no build step to run.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1] / "prototype" / "tokens"
SRC = ROOT / "tokens.json"
OUT = ROOT / "tokens.css"


def var_name(key: str) -> str:
    return "--" + key.replace("_", "-")


def theme_block(selector: str, colors: dict) -> str:
    lines = [f"{selector} {{"]
    for key, value in colors.items():
        lines.append(f"  {var_name(key)}: {value};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    tokens = json.loads(SRC.read_text())
    themes = tokens["themes"]
    parts = [
        "/* Generated by design/tools/build_tokens.py from tokens.json. Do not edit by hand. */",
        f"/* tokens version {tokens['version']} — {tokens['status']} */",
    ]

    # Theme-independent scalars
    root = [":root {"]
    for k, v in tokens["space"].items():
        root.append(f"  --space-{k}: {v}px;")
    for k, v in tokens["radius"].items():
        root.append(f"  --radius-{k}: {v}px;")
    root.append(f"  --hit-min: {tokens['touch']['min']}px;")
    root.append(f"  --hit-frequent: {tokens['touch']['frequent']}px;")
    root.append(f"  --font-ui: {tokens['type']['ui']};")
    root.append(f"  --font-mono: {tokens['type']['mono']};")
    root.append("  --fs-scale: 1;")
    for k, v in tokens["type"]["sizes"].items():
        root.append(f"  --fs-{k}: calc({v}px * var(--fs-scale));")
    root.append(f"  --label-tracking: {tokens['type']['label_tracking']};")
    st = tokens["motion"]["state_ms"]
    ws = tokens["motion"]["workspace_ms"]
    root.append(f"  --motion-state-fast: {st[0]}ms;")
    root.append(f"  --motion-state: {st[1]}ms;")
    root.append(f"  --motion-workspace-fast: {ws[0]}ms;")
    root.append(f"  --motion-workspace: {ws[1]}ms;")
    ins = tokens["insets"]
    root.append(f"  --inset-status: {ins['status_bar']}px;")
    root.append(f"  --inset-gesture: {ins['gesture_bar']}px;")
    root.append(f"  --gutter: {ins['side_gutter']}px;")
    vp = tokens["viewport"]["default"]
    root.append(f"  --vp-w: {vp['w']}px;")
    root.append(f"  --vp-h: {vp['h']}px;")
    g = tokens["glass"]
    root.append(f"  --glass-blur: {g['blur_balanced_px']}px;")
    root.append(f"  --glass-blur-enhanced: {g['blur_enhanced_px']}px;")
    root.append(f"  --glass-saturate: {g['saturate']};")
    root.append("}")
    parts.append("\n".join(root))

    # Themes. Daylight is the default on :root so the page is never unstyled.
    parts.append(theme_block(":root, :root[data-theme='daylight']", themes["daylight"]))
    parts.append(theme_block(":root[data-theme='lowlight']", themes["lowlight"]))
    parts.append(theme_block(":root[data-theme='contrast']", themes["contrast"]))

    # Font scale and tier hooks (values only; behaviour lives in app.css / materials.css)
    scales = tokens["type"]["font_scales"]
    for s in scales:
        parts.append(f":root[data-fontscale='{s}'] {{ --fs-scale: {s / 100:g}; }}")

    OUT.write_text("\n\n".join(parts) + "\n")
    print(f"wrote {OUT.relative_to(ROOT.parents[2])}")


if __name__ == "__main__":
    main()
